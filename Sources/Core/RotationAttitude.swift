import Foundation

/// Representation of the various rotation attitudes.
public enum RotationAttitude {
    
    /// An up-down (x) rotation attitude.
    case pitch
    
    /// A left-right (y) rotation attitude.
    case yaw
    
    /// A side-side (z) rotation attitude.
    case roll
    
}
